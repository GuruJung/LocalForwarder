#!/usr/bin/env python3
"""Validate the shared catalogs and emit dependency-free native lookup tables."""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ('en', 'ko', 'zh-Hans', 'zh-Hant', 'ja', 'es', 'de')
TOKEN = re.compile(r'\{([A-Za-z][A-Za-z0-9_]*)\}')
KEY = re.compile(r'[a-z][a-z0-9_.]*\Z')


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'duplicate key: {key}')
        result[key] = value
    return result


def placeholders(text):
    stripped = TOKEN.sub('', text)
    if '{' in stripped or '}' in stripped:
        raise ValueError('invalid placeholder syntax')
    return set(TOKEN.findall(text))


def validate(catalogs):
    if set(catalogs) != set(LANGUAGES):
        raise ValueError('exactly seven supported language catalogs are required')
    english = catalogs['en']
    if not isinstance(english, dict) or not english:
        raise ValueError('English catalog must be a nonempty object')
    for language in LANGUAGES:
        entries = catalogs[language]
        if not isinstance(entries, dict):
            raise ValueError(f'{language}: catalog must be an object')
        missing, extra = set(english) - set(entries), set(entries) - set(english)
        if missing or extra:
            raise ValueError(f'{language}: missing={sorted(missing)}, extra={sorted(extra)}')
        for key, value in entries.items():
            if not isinstance(key, str) or not KEY.fullmatch(key):
                raise ValueError(f'{language}: invalid key {key!r}')
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f'{language}/{key}: translation must be a nonempty string')
            if any(ord(char) < 32 and char not in '\n\t\r' for char in value):
                raise ValueError(f'{language}/{key}: invalid control character')
            try:
                value.encode('utf-8')
                tokens = placeholders(value)
                if tokens != placeholders(english[key]):
                    raise ValueError('placeholder names differ from English')
            except (UnicodeError, ValueError) as error:
                raise ValueError(f'{language}/{key}: {error}') from error
    return catalogs


def load_catalogs(directory):
    return validate({language: json.loads((directory / (language + '.json')).read_text(encoding='utf-8'),
                                        object_pairs_hook=unique_object)
                     for language in LANGUAGES})



def validate_references(root, catalogs):
    """Reject production calls to untranslated keys, including test hooks in UI code."""
    reference = re.compile(r'"((?:mac|win)\.[a-z0-9_.]+)"')
    for subtree in ('macos/Sources', 'windows/src'):
        for path in sorted((root / subtree).rglob('*')):
            if path.suffix not in ('.swift', '.cpp', '.hpp') or path.name in (
                'GeneratedTranslations.swift', 'generated_translations.hpp'
            ):
                continue
            missing = set(reference.findall(path.read_text(encoding='utf-8'))) - set(catalogs['en'])
            if missing:
                raise ValueError(f'{path.relative_to(root)}: unknown message keys {sorted(missing)}')


def quoted(text):
    # JSON quoting is also valid for these UTF-8 C++/Swift string literals.
    # Escape U+2028/2029 as literal characters, not JSON-only unicode escapes.
    return json.dumps(text, ensure_ascii=False)


def generated(catalogs):
    swift = ['// Generated by scripts/localization.py; edit localization/*.json instead.',
             'enum GeneratedTranslations {', '    static let values: [String: [String: String]] = [']
    cpp = ['// Generated by scripts/localization.py; edit localization/*.json instead.',
           '#pragma once', '#include <map>', '#include <string>',
           'namespace lf::generated {',
           'inline const std::map<std::string, std::map<std::string, std::string>> catalogs = {']
    for language in LANGUAGES:
        swift.append(f'        {quoted(language)}: [')
        cpp.append(f'    {{{quoted(language)}, {{')
        for key, value in sorted(catalogs[language].items()):
            swift.append(f'            {quoted(key)}: {quoted(value)},')
            cpp.append(f'        {{{quoted(key)}, {quoted(value)}}},')
        swift.append('        ],')
        cpp.append('    }},')
    swift += ['    ]', '}', '']
    cpp += ['};', '}', '']
    return {'macos/Sources/LocalForwarderCore/GeneratedTranslations.swift': '\n'.join(swift),
            'windows/src/generated_translations.hpp': '\n'.join(cpp)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='validate without changing generated files')
    args = parser.parse_args(argv)
    try:
        catalogs = load_catalogs(ROOT / 'localization')
        validate_references(ROOT, catalogs)
        for relative, content in generated(catalogs).items():
            path = ROOT / relative
            if args.check:
                if not path.is_file() or path.read_text(encoding='utf-8') != content:
                    raise ValueError(f'{relative} is stale; run python3 scripts/localization.py')
            else:
                path.write_text(content, encoding='utf-8')
        print(f'Validated {len(catalogs["en"])} messages in {len(LANGUAGES)} languages.')
        return 0
    except (OSError, ValueError, TypeError) as error:
        print(f'Localization error: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
