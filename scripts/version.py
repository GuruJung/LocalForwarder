#!/usr/bin/env python3
"""The repository VERSION is the sole manually maintained product version."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SWIFT = Path('macos/Sources/LocalForwarderCore/ProductVersion.swift')


def read_version(root=ROOT):
    value = (root / 'VERSION').read_text(encoding='utf-8').strip()
    if not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', value):
        raise ValueError('VERSION must be major.minor.patch without leading zeroes or suffixes')
    # CFBundleVersion allows four/two/two digits, within Windows WORD limits.
    if any(part > limit for part, limit in zip(map(int, value.split('.')), (9999, 99, 99))):
        raise ValueError('VERSION exceeds platform limits (9999.99.99)')
    return value


def swift_source(value):
    return ('// Generated by scripts/version.py --write from VERSION. Do not edit.\n'
            'public enum ProductVersion {\n'
            f'    public static let current = "{value}"\n'
            '}\n')


def check_tag(tag, value):
    if tag != 'v' + value:
        raise ValueError(f'Tag {tag!r} must equal v{value}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--write', action='store_true')
    action.add_argument('--check', action='store_true')
    action.add_argument('--print', action='store_true', dest='print_version')
    parser.add_argument('--tag', help='Require an exact v<version> release tag')
    args = parser.parse_args()
    try:
        value = read_version()
        if args.tag is not None:
            check_tag(args.tag, value)
        path = ROOT / SWIFT
        if args.write:
            path.write_text(swift_source(value), encoding='utf-8')
        elif args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != swift_source(value):
                raise ValueError('Generated Swift version is stale; run python3 scripts/version.py --write')
        else:
            print(value)
    except (OSError, ValueError) as error:
        parser.exit(1, f'{error}\n')


if __name__ == '__main__':
    main()
